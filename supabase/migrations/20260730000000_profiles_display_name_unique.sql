-- =============================================================================
-- profiles.display_name 중복을 DB 차원에서 막는다 (대소문자 무시)
-- =============================================================================
-- 배경: 닉네임 중복 검사는 지금까지 **앱에만** 있었다 — 입력 디바운스 조회 + 저장 직전 재확인.
--   두 검사 사이(그리고 재확인과 update 사이)에는 여전히 창이 열려 있어서, 동시에 같은 닉네임을
--   저장하면 둘 다 통과한다. 애플리케이션 검사는 경합을 좁힐 뿐 없애지 못한다 — 진짜 보장은
--   DB 제약뿐이다.
--
-- 왜 지금인가: 적용 시점의 실측으로 **기존 중복 0건**(프로필 5건, 빈 닉네임 0건)이었다.
--   사용자가 늘어난 뒤에는 중복 정리가 선행돼야 해서 훨씬 비싸진다.
--
-- ⚠ `lower(display_name)` 인 이유 — btrim 을 쓰지 않는다:
--   앱의 중복 검사는 `ilike(display_name, <입력값>)` 이다. 즉 **저장된 값 그대로**를
--   대소문자만 무시해 비교한다. 인덱스가 btrim 까지 적용하면 앱은 "사용 가능"이라 했는데
--   DB 는 23505 로 거절하는 불일치가 생긴다(가입 트리거가 만든 옛 행에는 공백이 남아 있을 수 있다).
--   인덱스 의미는 앱의 비교 의미와 **정확히 같아야** 한다.
--
-- 이 인덱스가 걸린 뒤 동시 저장의 패자는 23505 를 받는다. 앱은 그것을 "이미 사용 중"으로
-- 번역한다(pages/Community/CommunityProfilePage/hooks/useProfileEditor.ts).

create unique index if not exists profiles_display_name_lower_key
  on public.profiles (lower(display_name));
