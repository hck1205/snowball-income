-- =============================================================================
-- 공유 스냅샷 — 쓰기 경로를 닫는다 (2026-08-09)
-- =============================================================================
--
-- ## 무엇을 하는가
--
-- `create_shared_snapshot` 의 EXECUTE 권한을 회수한다. `get_shared_snapshot`(읽기)은 **그대로 둔다.**
-- 즉 새 `?s=` 링크는 더 이상 만들어지지 않고, **이미 나간 링크는 계속 열린다.**
--
-- ## 왜
--
-- 이 RPC 는 로그인 없이 누구나 부를 수 있었다. anon 키는 클라이언트 번들에 들어 있어 공개고,
-- 숨길 수 있는 종류가 아니다(브라우저가 써야 한다). 그런데 저장분에는
--   · 호출 횟수 제한이 없고
--   · 만료가 없고(`expires_at` 기본 null)
--   · 정리하는 작업도 없다
-- 한 건이 최대 64KB 이므로 반복 호출만으로 무료 플랜 용량을 채울 수 있는 상태였다. 그러면 진짜
-- 사용자가 공유를 못 만들고, 심하면 같은 DB 를 쓰는 커뮤니티 기능까지 함께 멈춘다.
--
-- 원래 마이그레이션(20260720000000)도 이걸 알고 있었다 — "남용 방어(레이트리밋·용량 상한·주기적
-- 만료 정리)는 후속 과제로 남긴다". 그 후속 과제를 하는 대신 **길 자체를 닫았다.**
--
-- ## 🔴 닫아도 되는 이유 — 실측했다
--
-- DB 경로가 존재한 근거는 둘이었는데 둘 다 서 있지 않았다.
--
-- 1. "URL 에 다 담으면 길이가 터진다"
--    → `test/share/shareLengthCensus.test.ts` 가 실제 인코더 + 실제 프리셋 218종목으로 잰다.
--      4000자 상한을 넘기려면 **73종목**이 필요하다. 30종목 1823자(상한의 46%), 50종목 2790자.
--      배당 포트폴리오에서 73종목은 사실상 안 나온다.
--    ⚠ "예전엔 인코딩이 뚱뚱해서 필요했다"도 아니다 — v3 압축 인코딩(2026-02-18)이 DB 경로
--      (2026-07-18)보다 다섯 달 **먼저** 들어와 있었다.
-- 2. "링크 미리보기 카드를 그리려면 서버가 payload 를 읽어야 한다"
--    → `?share=` 링크도 카드가 정상으로 그려진다. 서버리스 함수가 lz-string 을 직접 푼다
--      (server/handlers/Og 의 `resolveCardModel` 마지막 줄).
--
-- 남는 이득은 "URL 이 22자라 보기 좋다" 하나였고, 치르는 값이 위의 남용 노출이었다.
--
-- ## ⚠ 되돌리는 법 (레이트리밋을 붙이고 다시 열고 싶다면)
--
--   grant execute on function public.create_shared_snapshot(jsonb) to anon, authenticated;
--
-- 그리고 클라이언트에서 `createShareLink` 가 다시 DB 를 먼저 시도하게 되돌린다
-- (pages/Main/hooks/persistence/usePortfolioPersistence.ts). **다시 열 때는 레이트리밋을 함께
-- 붙여라** — 안 그러면 이 파일이 닫은 구멍이 그대로 돌아온다.
--
-- ## 왜 함수를 drop 하지 않는가
--
-- drop 하면 되돌릴 때 정의를 다시 써야 하고, key 생성 로직(base64url 122bit·충돌 재시도)이
-- 그 함수 안에만 있다. 권한만 회수하면 로직은 남고 노출만 사라진다 — 되돌리기가 한 줄이 된다.
--
-- 멱등성: revoke 는 이미 없는 권한에도 안전하다. 재실행해도 결과가 같다.
-- =============================================================================

do $$
begin
  if to_regprocedure('public.create_shared_snapshot(jsonb)') is null then
    raise notice 'create_shared_snapshot 이 없다 — 이미 정리됐거나 아직 안 만들어졌다. 건너뛴다.';
    return;
  end if;

  /*
   * 🔴 public 에서 **먼저** 회수한다. anon·authenticated 는 public 을 상속하므로, 역할에서만 빼고
   * public 을 남기면 아무것도 달라지지 않는다 — 20260808000000 에서 같은 함정을 적어 뒀다.
   */
  revoke execute on function public.create_shared_snapshot(jsonb) from public, anon, authenticated;

  raise notice 'create_shared_snapshot: EXECUTE 회수 완료 (읽기 RPC 는 그대로)';
end
$$;

-- =============================================================================
-- 읽기 경로가 살아 있는지 못 박는다 — 이 파일의 요점은 "쓰기만" 닫는 것이다.
-- =============================================================================
--
-- 위 do 블록이 실수로 읽기까지 회수하거나, 나중에 누가 정리하다 같이 지우면 **이미 나간 공유
-- 링크가 전부 죽는다.** 그건 사용자 자산이라 절대 안 된다. 그래서 여기서 명시적으로 다시 준다
-- (이미 있으면 no-op).
do $$
begin
  if to_regprocedure('public.get_shared_snapshot(text)') is null then
    raise warning 'get_shared_snapshot 이 없다 — 기존 ?s= 공유 링크를 열 수 없는 상태다!';
    return;
  end if;

  grant execute on function public.get_shared_snapshot(text) to anon, authenticated;
end
$$;

