-- =============================================================================
--   - create_shared_snapshot: EXECUTE 회수 → 새 ?s= 링크 생성 불가(남용 경로 차단)
--   - get_shared_snapshot   : EXECUTE 유지 → 기존 ?s= 링크는 계속 열린다
--   - shared_snapshots 테이블·데이터·함수 정의는 **무변경**(되돌리기는 grant 한 줄)
--   - 앱은 lz-string ?share= 한 길로만 링크를 만든다(실측상 73종목까지 담긴다)
-- =============================================================================
