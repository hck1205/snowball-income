/**
 * 결과 영역의 **묶음**.
 *
 * 왜 생겼나(2026-08-03 2차 리워크): 시뮬레이터의 결과는 [시나리오 탭] · [알림] · [카드 여덟 장]이
 * 페이지 배경 위에 **각자 떠 있는 형제들**이었다. 그래서 탭이 무엇을 전환하는지, 카드가 어디까지
 * 한 덩어리인지 화면이 말하지 않았다 — 탭의 아래 봉합선은 1px 실선 하나로 끝나고 그 아래는 다시
 * 페이지 배경이었다. 이 보드가 그 셋을 **문서 하나**로 묶는다: 머리(탭) → 알림 → 본문(격자).
 *
 * ── 🔴 2026-08-03 (흰 캔버스 전환): 묶는 수단을 **테두리 → 봉합선 + 정렬**로 바꿨다 ────────────
 *
 * 종전에는 이 보드가 `1px border + DATA_RADIUS` 로 된 **큰 사각형**이었다. 그 처방은 회색 캔버스
 * (`bg #f8f9fa`) 위에서 성립했다 — 그때 카드 테두리는 **1.19:1** 이라 사실상 안 보였고, 이 프레임이
 * 결과 영역에서 유일하게 보이는 선이었다. 라이트 `bg` 가 순백이 되면서 전제가 두 군데서 깨졌다:
 *
 *  ① 카드 테두리가 **1.19 → 1.49:1** 로 올라갔다(`shared/styles/presets/velog.ts`).
 *     이제 프레임과 카드가 **같은 색·같은 두께**의 선이고, 둘 사이 간격은 21px 다(1280 실측:
 *     프레임 x=53, 카드 x=74). 21px 떨어진 같은 무게의 평행선 둘은 위계가 아니라 **겹선**이다 —
 *     그릇과 내용물이 같은 목소리로 말하면 어느 쪽도 그릇으로 읽히지 않는다.
 *  ② 더 나쁜 것은 **끝선이 갈라졌다는 것**이다. 이 화면의 다른 전폭 요소(히어로 · "다른 구성으로
 *     바꿔 보세요" 카드 · 시세 스트립)는 전부 x=53 에서 시작하는데, 보드 안의 결과 카드만 x=74 였다.
 *     흰 캔버스에서는 **경계가 구조를 말하는 유일한 채널**이라, 끝선이 둘이면 화면이 통째로 흔들린다.
 *
 * 그래서 프레임을 벗고, 묶음은 원래 갖고 있던 두 가지로만 말한다:
 *  - **봉합선** — 시나리오 탭 줄의 밑줄(`ScenarioTabsRow` 의 `border-bottom`)이 이제 콘텐츠 폭
 *    전체(1160)를 가로지른다. 탭 패널의 고전적 형태 그대로다: 활성 탭이 그 선을 덮어 아래 판과 잇는다.
 *  - **정렬** — 머리·알림·본문이 페이지의 **단 하나의 끝선**을 공유한다.
 *  그 위에 막 머리띠(`ActBand` 의 01/02/03 + 룰)가 장(章)을 끊는다.
 *
 * 이 처방은 새로 지어낸 것이 아니다 — 좁은 폭(`media.down('layout')`)에서는 **원래부터** 프레임을
 * 벗고 이렇게 그리고 있었다. 흰 캔버스에서는 그 규칙이 전 폭에서 옳아졌을 뿐이다.
 *
 * 🔴 **프레임을 되돌리려거든 먼저 두 가지를 재라**: 카드 테두리 대비(1.4:1 대 이상이면 프레임은
 *    겹선이 된다)와 좌우 끝선(보드 안팎의 전폭 요소가 같은 x 에서 시작하는가). 둘 중 하나라도
 *    어긋나면 프레임은 정보가 아니라 소음이다.
 * 🔴 면(배경)도 **채우지 않는다.** 처음에는 `surfaceSunken` 으로 깔았는데, 그 값은 **부속 카드
 *    (`Card tone="sunken"`)의 배경과 같은 토큰**이라 `전량 매도한다면` 카드 — 테두리도 그림자도 없이
 *    면색만으로 격을 말하는 유일한 카드 — 가 배경과 정확히 같은 색이 되어 **화면에서 사라졌다**
 *    (실측 rgb(241,243,245) : rgb(241,243,245)). `surfaceMuted` 도 답이 아니다 — 다크에서 `surface`
 *    보다 밝아 카드가 보드보다 가라앉아 보인다. 카드의 격(주역=그림자 · 본문=테두리 · 부속=면색)은
 *    전부 **페이지 배경을 기준으로** 정해져 있으므로 배경은 비워 두어야 한다.
 */
/*
 * 🔴 `display: block` 이다 — **grid 로 되돌리면 아래 머리 줄의 sticky 가 죽는다**(2026-08-17).
 * grid item 의 sticky 는 자기 **grid area(= 자기 행) 안에서만** 움직인다. 머리 줄은 자기 높이만큼의
 * 행을 차지하므로 이동 범위가 0 이 되어 사실상 static 이다(`Main.shared.styled.ts` 에 같은 함정이
 * 적혀 있다 — 히어로 액션은 그래서 fixed 승격을 택했다). 흐름(block)에서는 머리 줄의 컨테이닝 블록이
 * **보드 전체**라, 결과 격자를 지나는 동안 탭이 헤더 아래에 붙어 있는다.
 * ⚠ `gap: 0` 이었으므로 grid 를 벗어도 간격은 변하지 않는다(세 슬롯이 각자 패딩으로 띈다).
 *   자식들은 margin 을 쓰지 않으므로 마진 상쇄도 생기지 않는다.
 */
export const BoardRoot = styled.section`
  display: block;
  min-width: 0;
  border: 0;
  background: transparent;
`;

/**
 * 보드 머리 — 시나리오 탭 줄이 앉는 자리.
 *
 * 아래쪽 패딩이 0 인 것이 의도다: 탭의 밑줄(`ScenarioTabsRow` 의 border-bottom)이 곧 머리와 본문의
 * 경계선이라, 그 아래에 여백을 더 주면 선이 허공에 뜬다.
 *
 * 🔴 좌우 패딩은 **0 이어야 한다** — 이 줄의 밑줄이 결과 영역의 봉합선이고, 봉합선은 카드와 같은
 * 끝선에서 시작해 같은 끝선에서 끝나야 판을 잇는다. 안쪽으로 들여쓰면 선이 카드보다 짧아져,
 * 탭이 아래 판을 덮는 게 아니라 그 위에 얹힌 별개 조각으로 보인다.
 *
 * 위쪽 12px 은 프레임이 있던 시절의 값을 그대로 지킨 것이다 — 프레임을 벗었다고 히어로와의 간격까지
 * 좁히면 탭 줄이 위 카드에 붙어 그 카드의 꼬리처럼 읽힌다(격자 gap 20 + 이 값 12 = 32px).
 * 붙어 있는 동안에는 그 12px 이 **헤더 hairline 과 탭 사이의 숨구멍**이 된다(히어로 액션의 PIN_GAP 8 과
 * 같은 역할이라 값을 따로 두지 않았다).
 *
 * ── 🔴 스크롤하면 앱 헤더 아래에 붙는다 (2026-08-17 사용자 지시: "탭 영역을 fixed sticky 로") ──────
 *
 * `top` 은 **실측 헤더 높이**(`appHeaderHeight`)다. 88px 같은 상수를 적으면 헤더가 한 줄에서 두 줄로
 * 바뀔 때 탭이 헤더 뒤로 숨는다 — 이 레포에서 세 번 고쳐 쓴 값이라 상수를 금지한다
 * (`headerSurface.ts` 의 그 변수 주석).
 *
 * 🔴 **배경을 반드시 칠한다.** 이 줄은 원래 투명이었고(보드가 면을 갖지 않는다는 규칙 — 위 `BoardRoot`
 *    주석), 투명한 채로 붙이면 아래를 지나가는 결과 카드가 탭 글자와 겹쳐 읽힌다. 면색은 `surface`
 *    계열이 아니라 **페이지 배경(`bg`)** 이다: 이 줄은 카드가 아니라 페이지의 일부이고, 카드 면색을
 *    쓰면 붙는 순간 없던 카드가 하나 생긴 것처럼 보인다.
 *    ⚠ body 의 오로라 글로우는 `background-attachment: fixed` 가 아니라 함께 스크롤되므로, 붙어 있는
 *      동안 이 줄 뒤에 있는 것은 단색 `bg` 다 — 그래서 단색으로 맞아떨어진다.
 *
 * 층위는 `stickyBar`(9): 결과 카드(1~2) 위를 지나가고, 앱 헤더(30) 아래로 들어가며, 드로어
 * 계열(55~60)이 열리면 그 아래에 깔린다.
 * 🔴 **`stickyAction`(10)으로 올리지 마라.** 그 값이던 동안 이 바가 고정된 "투자 설정" 버튼을
 *    삼켰다(같은 층 → DOM 순서로 승자 결정, 보드가 히어로보다 뒤 + 불투명 배경). 그 버튼은
 *    이 바 **위에** 떠야 한다 — 근거와 실측은 `tokens.ts` 의 `stickyBar` 주석.
 *
 * ⚠ sticky 는 **스태킹 컨텍스트**를 만든다. 탭의 이름표 툴팁(`ScenarioTabTooltip`)이 `position: fixed`
 *   인데도 안전한 이유는 그것이 `modalRoot` 로 **포털**되어 이 컨텍스트 밖에서 그려지기 때문이다
 *   (`MainRightPanel` 의 createPortal). 툴팁을 이 안으로 되돌리면 z-index 2000 이 이 층(10)에 갇힌다.
 */
