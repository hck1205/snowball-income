/**
 * 물가상승률 **가정** — 이 저장소에서 물가를 다루는 유일한 자리 (2026-11-01 신설).
 *
 * ## 🔴 이것은 관측이 아니라 가정이다
 * 가격·배당률·지급월은 스냅샷에서 오는 **실측**이고, 기대총수익률은 큐레이터의 **가정**이다
 * (`shared/constants/marketData/applyMarketData.ts` 의 계약). 물가는 그 어느 쪽도 아니다 —
 * 미래 값이라 관측이 불가능하고, 우리가 큐레이션한 종목별 값도 아니다. **사용자가 고르는 입력**이다.
 *
 * 그래서 이 파일은 숫자를 하나로 못 박지 않고 **선택지와 그 근거**를 준다. 화면은 고른 값을
 * 반드시 "가정"으로 표기한다(`basis: 'assumed'`). 표기가 사라지면 "물가 2%"가 실측처럼 읽히는데,
 * 그건 이 레포의 "지어낸 숫자 0" 규칙 위반이다.
 *
 * ## 기본값이 2.0% 인 이유
 * 한국은행의 **물가안정목표가 2.0%** 다(2019년부터 단일 수치 목표). 장기 가정으로 쓸 수 있는
 * 숫자 중에 유일하게 *공표된 근거*가 있는 값이라 기본값으로 삼았다. 과거 실적 평균(10년 ~1.9%)도
 * 여기에 가깝다.
 *
 * ⚠ 2.5%·3.0% 는 "최근 체감이 더 높다"는 사용자를 위한 선택지이고 공표 근거가 없다 — 그래서
 *   기본값이 아니다. 더 높은 물가를 고르면 배당 인상률이 물가를 이기는 종목이 줄어든다.
 *
 * ## 🔴 미래가치 환산은 하지 않는다 (2026-11-01 사용자 결정)
 * "10년 뒤 월 250만원의 구매력은 얼마" 같은 환산을 **일부러 넣지 않았다.** 그러려면 몇 년 뒤인지를
 * 또 가정해야 하고, 가정 위에 가정을 쌓은 숫자가 화면에서 가장 큰 글씨가 된다. 물가는 **배당 인상률과
 * 나란히 비교하는 데까지만** 쓴다 — 그 비교는 양쪽 다 연율이라 추가 가정이 0 이다.
 */

/**
 * 화면이 제시하는 물가상승률 선택지(%). 순서 = 노출 순서(낮은 것부터).
 * 🔴 첫 항목이 기본값이라는 규약을 두지 않았다 — `DEFAULT_INFLATION_RATE` 가 따로 정본이다
 *   (배열 순서를 바꾸는 사람이 기본값까지 바꿔 버리는 사고를 막는다).
 */
export const INFLATION_RATE_CHOICES = [2.0, 2.5, 3.0] as const;

export type InflationRateChoice = (typeof INFLATION_RATE_CHOICES)[number];

/** 기본 물가상승률(%) — 한국은행 물가안정목표. 근거는 이 파일 머리말. */
export const DEFAULT_INFLATION_RATE: InflationRateChoice = 2.0;

/** 고른 값의 근거를 한 줄로. 기본값만 공표 근거가 있고 나머지는 "체감" 이라고 말한다. */
export const INFLATION_RATE_BASIS_LABEL: Record<InflationRateChoice, string> = {
  2.0: '한국은행 물가안정목표',
  2.5: '목표보다 높게 보는 가정',
  3.0: '목표보다 크게 높게 보는 가정'
};

/** 사용자가 넘긴 값이 선택지 안에 있는가. 쿼리·저장값을 믿지 않는다. */
export const isInflationRateChoice = (value: unknown): value is InflationRateChoice =>
  INFLATION_RATE_CHOICES.includes(value as InflationRateChoice);
