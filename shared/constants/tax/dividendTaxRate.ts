/**
 * 배당소득세율의 **기본값 결정** — 상장지에 따라 갈린다 (2026-08-14 신설).
 *
 * ## 🔴 왜 15% 와 15.4% 가 다른가
 * | 보유 형태 | 미국 원천징수 | 국내 추가 | 실효 |
 * |---|---|---|---|
 * | 미국 상장 직접 보유 (SCHD·JEPI·O …) | 15% | **없음** — 국내 세율 14% 가 이미 뗀 15% 보다 낮아 추가 징수가 없다 | **15.0%** |
 * | 국내 상장 (`.KS`/`.KQ`) | — | 소득세 14% + 지방소득세 1.4% | **15.4%** |
 *
 * 두 값의 차이는 0.4%p 지만 20~30년 복리에서는 결과가 눈에 띄게 갈리고, 무엇보다 **미국 배당 ETF 를
 * 다루는 사이트가 미국 배당 세율을 틀리면 계산 전체의 신뢰가 무너진다.**
 *
 * ## 🔴 이 함수가 고치는 진짜 결함은 "미입력 = 0%" 였다
 * 세율은 폼에서 **선택 입력**(`taxRate?: number`)이라, 비우거나 세율 없이 저장된 페이로드·공유 링크는
 * 엔진에서 `0%` 로 계산됐다 — 세금이 통째로 빠진 **과대추정**이고 화면에는 아무 경고도 없었다.
 * 이제 미입력은 0% 가 아니라 **그 종목의 정확한 기본 세율**로 해결된다.
 *
 * ## 적용 범위
 * - 배당소득세만 다룬다. 해외주식 양도소득세(22%)·금융소득종합과세는 `index.ts` 의 별도 상수다.
 * - ISA·연금저축 계좌의 과세이연/분리과세는 **계좌 유형 입력이 없어** 다루지 않는다. 사용자가 폼에서
 *   직접 낮은 세율을 넣는 것으로 표현한다(입력값은 언제나 이 기본값을 이긴다).
 * - 국내 상장 종목의 세 갈래(`KoreanTaxCategory`)는 **매매차익** 과세가 갈리는 것이고 **배당**에는
 *   셋 다 15.4% 가 붙는다 — 그래서 배당 세율 기본값은 상장지만 보면 된다.
 */
import { isKoreanListedTicker, KOREAN_DIVIDEND_TAX_RATE } from './koreanTaxCategory';

/**
 * 미국 상장 종목의 배당 실효세율(%). 미국에서 15% 원천징수로 끝난다.
 *
 * ⚠ 국내 세율 14% 를 더하지 않는다 — 외국납부세액공제로 **더 낸 쪽만 정산**되는데 이미 뗀 15% 가
 * 국내 14% 보다 높아 추가 징수가 없다. 15 + 15.4 로 겹쳐 세면 세부담이 두 배로 잡힌다.
 */
export const US_LISTED_DIVIDEND_TAX_RATE = 15;

/**
 * 그 종목에 붙는 **기본 배당소득세율(%)**. 사용자가 폼에 값을 넣었으면 그 값이 항상 이긴다 —
 * 이 함수는 **미입력일 때만** 쓰인다.
 *
 * 판정 근거는 티커 표기다(`.KS`/`.KQ` = 국내 상장). 큐레이션이 접미사를 못 박아 두었기 때문에
 * 믿을 수 있다(`koreanDividendTickers.ts` — 야후가 틀린 접미사도 200 으로 답해서 자동 판정을 금지했다).
 */
export const resolveDefaultDividendTaxRatePercent = (ticker: string): number =>
  isKoreanListedTicker(ticker) ? KOREAN_DIVIDEND_TAX_RATE : US_LISTED_DIVIDEND_TAX_RATE;
