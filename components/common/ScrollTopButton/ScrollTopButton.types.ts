import type { RefObject } from 'react';

export type ScrollTopButtonProps = {
  /**
   * 맨 위로 이동한 **뒤 포커스를 넘길 요소**.
   *
   * 옵셔널이 아닌 이유: 버튼은 이동 직후 임계 아래로 내려가 **스스로 사라진다**. 포커스를 그대로 두면
   * 키보드 사용자는 사라진 요소에 남아 다음 Tab이 문서 어디서 시작될지 알 수 없다. "포커스를 어디에
   * 둘 것인가"는 이 부품을 쓰는 화면이 반드시 답해야 하는 질문이라 프롭으로 강제한다.
   *
   * 🔴 대상은 **포커스를 받을 수 있어야** 한다 — 원래 포커스 가능한 요소이거나 `tabIndex={-1}` 을
   * 가진 요소다. 아니면 `focus()` 가 조용히 아무 일도 하지 않고 포커스가 body 로 떨어진다.
   * 두 소비처의 선택:
   *  · 커뮤니티 상세 → 글 제목 `h1`(스크린리더가 제목을 읽어 "맨 위로 왔다"가 그대로 전달된다)
   *  · 랜딩 → 히어로 묶음 `div`(그 화면의 `h1` 은 공용 `PageHero` 안이라 ref 를 걸 자리가 없다)
   */
  focusRef: RefObject<HTMLElement>;
};
