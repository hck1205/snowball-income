import type { ReactNode } from 'react';

/**
 * 앱 전역 헤더의 슬롯 계약.
 *
 * 🔴 **페이지가 헤더를 다시 조립하지 않는다.** 브랜드 워드마크 · 라우트 메뉴 · 로그인(AuthControl) ·
 * 더보기(⋯) 는 `AppHeader` 가 직접 그리므로 어떤 페이지에서도 같은 자리에 같은 접근명으로 존재한다.
 * 아래 슬롯은 **그 공통 헤더에 페이지가 "더하는 것"만** 받는다 — 빼는 옵션은 일부러 두지 않았다.
 */
export type AppHeaderProps = {
  /**
   * 브랜드 워드마크를 감쌀 태그. 워드마크가 그 화면의 `h1` 을 겸할 때만 `'h1'`(페이지당 1개).
   * 티커 상세처럼 본문에 고유 `h1` 이 있는 화면은 기본값 `'span'` 을 쓴다.
   */
  brandAs?: 'h1' | 'span';
  /**
   * 컨트롤 줄 1열, 워드마크 **바로 오른쪽** — 그 화면의 상태 표시.
   * 지금 소비처는 시뮬레이터의 클라우드 동기화 표시 하나뿐이다.
   */
  status?: ReactNode;
  /**
   * 컨트롤 줄 2열(가운데) — 지금은 커뮤니티 갤러리의 인라인 검색.
   * 3컬럼 그리드(`1fr auto 1fr`)의 가운데 트랙이라 아랫줄 메뉴와 중심선이 구조적으로 일치한다.
   */
  center?: ReactNode;
  /**
   * 컨트롤 줄 3열 — 공용 컨트롤(로그인 · 더보기) **앞**에 붙는 페이지 전용 액션.
   * 예: 커뮤니티의 "글쓰기" 버튼과 모바일 검색 토글.
   */
  actions?: ReactNode;
  /**
   * 더보기(⋯) 교체 슬롯. 미지정이면 공용 `HeaderOverflowMenu`(앱 설치 · 테마)를 그린다.
   * 시뮬레이터만 PDF 리포트·튜토리얼이 붙은 자체 메뉴를 넣는다.
   */
  overflowMenu?: ReactNode;
  /**
   * 메뉴 줄 **아래**에 붙는 확장 영역(헤더 안, 전폭). 커뮤니티 모바일 검색 바가 유일한 소비처다.
   */
  below?: ReactNode;
  /**
   * 헤더 안쪽 컨테이너의 좌우 여백. 그 페이지 **본문 컨테이너와 같은 값**이어야 헤더와 본문의
   * 좌우 끝선이 맞는다(둘 다 max-width 1200). 기본값은 `FeatureLayout`·티커 셸이 쓰는 앱 표준이고,
   * 커뮤니티만 자기 `CommunityMain` 에 맞춘 값을 넘긴다.
   */
  contentGutter?: string;
};
